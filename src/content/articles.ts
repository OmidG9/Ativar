export function getArticle(slug: string): Article | undefined {
  return articles.find((article) => article.slug === slug);
}

export function getArticleCategory(category: string): ArticleCategory | undefined {
  return articleCategories.find((item) => item.title === category);
}

export function getRelatedArticles(slug: string, limit = 2): Article[] {
  const current = getArticle(slug);
  if (!current) return articles.slice(0, limit);

  const sameCategory = articles.filter(
    (article) => article.slug !== slug && article.category === current.category,
  );
  const otherCategories = articles.filter(
    (article) => article.slug !== slug && article.category !== current.category,
  );

  return [...sameCategory, ...otherCategories].slice(0, limit);
}
